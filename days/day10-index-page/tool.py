"""Day 10: index page builder and repo check.

Scans days/dayNN-name/ folders, builds INDEX.md (every tool grouped by roadmap phase),
and checks the repo conventions: each day has a README with a title, **What:** and
**Why:** lines, a tool.py, and is listed in the main README with a matching streak badge.

Usage:
    python days/day10-index-page/tool.py            # write INDEX.md
    python days/day10-index-page/tool.py --check    # CI: exit 1 if anything is wrong or stale
"""
import argparse
import re
import sys
from dataclasses import dataclass, field
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DAY_DIR_RE = re.compile(r"^day(\d{2,3})-(.+)$")
TITLE_RE = re.compile(r"^#\s+Day\s+(\d+):\s*(.+?)\s*$", re.MULTILINE)
WHAT_RE = re.compile(r"^\*\*What:\*\*\s*(.+)$", re.MULTILINE)
WHY_RE = re.compile(r"^\*\*Why:\*\*\s*(.+)$", re.MULTILINE)
BADGE_RE = re.compile(r"streak-day%20(\d+)%2F100")
PLACEHOLDERS = ("one sentence on what it does", "<Tool name>", "the real lab or research problem")

PHASES = [
    (1, 10, "Foundations and template"),
    (11, 20, "Nanomaterial and spectroscopy data"),
    (21, 30, "DFT and xTB workflows"),
    (31, 40, "Docking and MD"),
    (41, 50, "Synthesis and green chemistry"),
    (51, 60, "Machine learning for chemistry"),
    (61, 70, "Tools for students"),
    (71, 80, "Apps and visualization"),
    (81, 90, "Quality and reproducibility"),
    (91, 100, "Capstone"),
]
DAY_ONE = {"number": 1, "title": "Repo setup", "what": "License, README, requirements and the day template.",
           "path": "template/", "tests": False}


@dataclass
class Day:
    number: int
    title: str
    what: str
    path: str  # relative link, e.g. days/day02-smiles-to-3d/
    tests: bool
    errors: list[str] = field(default_factory=list)
    warnings: list[str] = field(default_factory=list)


def clip(text: str, limit: int = 150) -> str:
    """Shorten to a whole-word prefix and escape table pipes."""
    text = text.strip().replace("|", "\\|")
    if len(text) <= limit:
        return text
    return text[:limit].rsplit(" ", 1)[0].rstrip(",;:") + "..."


def scan_day(folder: Path) -> Day:
    """Read one days/dayNN-name folder and collect its metadata, errors and warnings."""
    m = DAY_DIR_RE.match(folder.name)
    number = int(m[1])
    name = folder.name
    day = Day(number, folder.name, "", f"days/{name}/", any(folder.glob("test_*.py")))
    readme = folder / "README.md"
    if not (folder / "tool.py").is_file():
        day.errors.append(f"{name}: missing tool.py")
    if not readme.is_file():
        day.errors.append(f"{name}: missing README.md")
        return day
    text = readme.read_text()
    title = TITLE_RE.search(text)
    if not title:
        day.errors.append(f"{name}: README must start with '# Day N: Title'")
    else:
        day.title = title[2]
        if int(title[1]) != number:
            day.errors.append(f"{name}: README says Day {title[1]} but the folder is day{number:02d}")
    what, why = WHAT_RE.search(text), WHY_RE.search(text)
    if not what:
        day.errors.append(f"{name}: README is missing the '**What:**' line")
    else:
        day.what = what[1]
    if not why:
        day.errors.append(f"{name}: README is missing the '**Why:**' line")
    if any(p in text for p in PLACEHOLDERS):
        day.errors.append(f"{name}: README still contains template placeholder text")
    example = folder / "example"
    if not example.is_dir() or not any(example.rglob("*")):
        day.warnings.append(f"{name}: no example/ files")
    if not day.tests:
        day.warnings.append(f"{name}: no test_*.py")
    return day


def scan_days(root: Path) -> list[Day]:
    folders = sorted(p for p in (root / "days").glob("day*") if p.is_dir() and DAY_DIR_RE.match(p.name))
    days = [scan_day(f) for f in folders]
    seen: dict[int, str] = {}
    for d in days:
        if d.number in seen:
            d.errors.append(f"{d.path}: day number {d.number} is also used by {seen[d.number]}")
        seen[d.number] = d.path
    return sorted(days, key=lambda d: d.number)


def render_index(days: list[Day]) -> str:
    rows = [Day(1, DAY_ONE["title"], DAY_ONE["what"], DAY_ONE["path"], False)] + [
        d for d in days if d.number != 1]
    lines = [
        "# Index of tools",
        "",
        "Generated by `days/day10-index-page/tool.py`. Do not edit by hand: change a tool's README and re-run it.",
        "",
        f"**{len(rows)} of 100 days done.** The plan for the rest is in [ROADMAP.md](ROADMAP.md).",
    ]
    for start, end, name in PHASES:
        phase = [d for d in rows if start <= d.number <= end]
        if not phase:
            continue
        lines += ["", f"## Phase {PHASES.index((start, end, name)) + 1} (Days {start}-{end}): {name}", "",
                  "| Day | Tool | What it does | Tests |", "|---|---|---|---|"]
        for d in phase:
            lines.append(f"| {d.number} | [{d.title}]({d.path}) | {clip(d.what)} | {'yes' if d.tests else '-'} |")
    return "\n".join(lines) + "\n"


def check_main_readme(root: Path, days: list[Day]) -> list[str]:
    """The main README must link every day folder and show the latest day in its streak badge."""
    readme = root / "README.md"
    if not readme.is_file():
        return ["README.md is missing"]
    text, errors = readme.read_text(), []
    for d in days:
        if d.path not in text:
            errors.append(f"README.md does not link {d.path}")
    badge = BADGE_RE.search(text)
    latest = max((d.number for d in days), default=1)
    if not badge:
        errors.append("README.md has no streak badge")
    elif int(badge[1]) != latest:
        errors.append(f"README.md streak badge says day {badge[1]} but the latest day folder is {latest}")
    return errors


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--root", default=str(ROOT), help="repository root (default: this repository)")
    ap.add_argument("--check", action="store_true", help="do not write; exit 1 on any problem or stale INDEX.md")
    ap.add_argument("-o", "--output", help="index file to write or check (default: <root>/INDEX.md)")
    args = ap.parse_args()

    root = Path(args.root)
    if not (root / "days").is_dir():
        print(f"error: no days/ folder in {root}", file=sys.stderr)
        return 2
    days = scan_days(root)
    errors = [e for d in days for e in d.errors] + check_main_readme(root, days)
    warnings = [w for d in days for w in d.warnings]
    for e in errors:
        print(f"[error] {e}")
    for w in warnings:
        print(f"[warn]  {w}")

    index = render_index(days)
    target = Path(args.output) if args.output else root / "INDEX.md"
    stale = not target.is_file() or target.read_text() != index
    if args.check:
        if stale:
            print(f"[error] {target.name} is out of date. Run: python days/day10-index-page/tool.py")
            errors.append("stale index")
        print(f"checked {len(days)} days: {len(errors)} errors, {len(warnings)} warnings")
        return 1 if errors else 0

    target.write_text(index)
    print(f"Wrote {target} ({len(days)} days, {len(errors)} errors, {len(warnings)} warnings)")
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
